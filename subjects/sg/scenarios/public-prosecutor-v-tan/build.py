"""Writes the four per-Act test files for the scenario Public Prosecutor v Tan (see SCENARIO.md).

l4 cannot import across subjects, so the scenario is four files, one in each subject's encodings/ directory, sharing one
set of facts.  The only things that pass between them are the Written Law Procedure Statements, which each Act's file
asserts equals what the CPC file hard-codes.  Run from this directory:  python build.py
"""
import sys, os
HERE = os.path.dirname(os.path.abspath(__file__))
SG = os.path.normpath(os.path.join(HERE, '..', '..'))
sys.path.insert(0, os.path.join(SG, 'misuse-of-drugs-act-1973', 'encodings', 'generators'))
from fixtures import Types, Out


def enc(slug):
    return os.path.join(SG, slug, 'encodings')


def fx(o, var, rec, true=(), **values):
    o.parts.append(o.t.fixture(var, rec, true, {k.replace('__', ' '): v for k, v in values.items()}) + '\n')


CASE = """-- SCENARIO: Public Prosecutor v Tan (scenarios/public-prosecutor-v-tan/SCENARIO.md).  Generated by build.py; do not edit.
-- Mr Tan is found holding packets of 4 g of diamorphine in a flat whose key he holds, with a weighing scale.
-- At the station he offers $5,000 to Officer Lim, a Government officer, to lose the exhibit.  The prosecution charges s 5(1) of the Misuse of Drugs Act 1973
-- and s 5(b) of the Prevention of Corruption Act 1960, and relies on his offer as a statement of an accused.
"""

MAXTERM = 'the__maximum__term__of__imprisonment__provided__by__law,__in__years'

# ---------------------------------------------------------------- MDA
T = Types(os.path.join(enc('misuse-of-drugs-act-1973'), 'mda-types.l4'))
o = Out(T, "IMPORT prelude\nIMPORT `mda-types`\nIMPORT `mda-offences`\nIMPORT `mda-presumptions`\nIMPORT `mda-punishment`\nIMPORT `mda-enforcement`\n\n" + CASE)
o.section("Tan: the drug, the presumptions, the offence, the punishment")
fx(o, 'diamorphine', 'Substance Facts',
   ['the thing is specified in Part 1, 2 or 3 of the First Schedule', 'the thing has the capacity to have a psychoactive effect'])
fx(o, 'Tan 4 g', 'Drug Quantity Facts', the__weight__of__diamorphine__in__grammes=4)
fx(o, 'Tan at the 2 g line', 'Drug Quantity Facts', the__weight__of__diamorphine__in__grammes=2)
fx(o, 'Tan holds the packets', 'Presumption Facts', ['the accused is proved to have had the thing in his or her possession'])
fx(o, 'Tan holds only the key', 'Presumption Facts', ['the keys of a place or premises'])
fx(o, 'Tan holds the packets and proves not for trafficking', 'Presumption Facts',
   ['the accused is proved to have had the thing in his or her possession', 'his or her possession of the thing was not for the purpose of trafficking'])
fx(o, 'Tan, the packets, nothing else', 'Trafficking Facts')
fx(o, 'Tan no antecedents', 'Antecedent Facts')
fx(o, 'no manufacture', 'Scheduled Quantity Facts')
o.assert_('`the thing is a controlled drug` `diamorphine`')
o.assert_('`the quantity possessed exceeds a figure in section 17` `Tan 4 g`')
o.assert_('NOT `the quantity possessed exceeds a figure in section 17` `Tan at the 2 g line`')
o.assert_('`possession for the purpose of trafficking is presumed under section 17` `Tan 4 g` `Tan holds the packets`')
o.assert_('NOT `possession for the purpose of trafficking is presumed under section 17` `Tan at the 2 g line` `Tan holds the packets`')
o.assert_('NOT `possession for the purpose of trafficking is presumed under section 17` `Tan 4 g` `Tan holds only the key`')
o.assert_('`possession of the drug is presumed under section 18(1)` `Tan holds only the key`')
o.assert_('`knowledge of the nature of the drug is presumed under section 18(2)` `Tan holds only the key`')
o.assert_('`knowledge of the nature of the drug is presumed under section 18(2)` `Tan holds the packets`')
o.assert_('`an offence under section 5(1) is made out` `Tan, the packets, nothing else` `diamorphine` TRUE')
o.assert_('NOT `possession for the purpose of trafficking is presumed under section 17` `Tan 4 g` `Tan holds the packets and proves not for trafficking`')
o.assert_('NOT `an offence under section 5(1) is made out` `Tan, the packets, nothing else` `diamorphine` FALSE')
P = '`the punishment on conviction of an offence under section 5(1) or 7` "5" `Class A drug` `Tan 4 g` `no manufacture` `Tan no antecedents`'
o.note('4 g is below every sixth-column band (10 g and up), so the Class A column of the Second Schedule governs: 5 to 20 years, not less than 5 strokes.')
o.assert_("NOT (%s)'s `the punishment is death`" % P)
o.assert_("(%s)'s `the maximum imprisonment in months` EQUALS 240" % P)
o.assert_("(%s)'s `the minimum imprisonment in months` EQUALS 60" % P)
o.assert_("(%s)'s `the minimum strokes of the cane` EQUALS 5" % P)
o.section("What the Act hands the Criminal Procedure Code")
o.note("These are the values cpc-tests-scenario-tan.l4 hard-codes as the Act's statement.")
S = "(`the Misuse of Drugs Act 1973's statement about its offences`)'s "
o.assert_(S + '`the Act` EQUALS "Misuse of Drugs Act 1973"')
o.assert_('NOT ' + S + '`the Act deems the offence to be an arrestable offence for the purposes of the Criminal Procedure Code 2010`')
o.assert_(S + '`the Act empowers the police to arrest without warrant for the offence`')
o.assert_(S + "`the Act shows the offence as triable by a District Court under that Act`")
o.assert_('NOT ' + S + "`the Act shows the offence as triable by a Magistrate's Court under that Act`")
o.write(os.path.join(enc('misuse-of-drugs-act-1973'), 'mda-tests-scenario-tan.l4'))

# ---------------------------------------------------------------- PCA
T = Types(os.path.join(enc('prevention-of-corruption-act-1960'), 'pca-types.l4'))
o = Out(T, "IMPORT prelude\nIMPORT `pca-types`\nIMPORT `pca-offences`\nIMPORT `pca-procedure`\n\n" + CASE)
o.section("Tan: the $5,000 offered to Officer Lim")
fx(o, '$5,000 in cash', 'Gratification Facts', ['the thing is money or a gift'])
fx(o, 'Lim, a Government officer', 'Agency Facts', ['the person was serving the Government'])
fx(o, 'no intermediary', 'Agency Facts')
fx(o, 'Tan offers to induce Lim, corruptly', 'Section 5 Facts',
   ['the accused gave, promised or offered a gratification', 'the accused acted corruptly',
    'the gratification was an inducement to, reward for, or on account of, any person doing or forbearing'])
fx(o, 'Tan offers, corruption not shown', 'Section 5 Facts',
   ['the accused gave, promised or offered a gratification',
    'the gratification was an inducement to, reward for, or on account of, any person doing or forbearing'])
fx(o, 'Lim is a Government officer and Tan has dealings with the Government', 'Presumption Facts',
   ['paid or given to, or received by, a person in the employment of the Government', 'received from, a person who has or seeks to have any dealing'])
fx(o, 'the same, contrary proved', 'Presumption Facts',
   ['paid or given to, or received by, a person in the employment of the Government', 'received from, a person who has or seeks to have any dealing', 'the contrary is proved'])
fx(o, 'no Government contract', 'Government Contract Facts')
o.assert_('`the thing is a gratification` `$5,000 in cash`')
o.assert_('`the person is an agent` `Lim, a Government officer`')
o.assert_('`an offence under section 5(b) is made out` `Tan offers to induce Lim, corruptly` `$5,000 in cash` FALSE')
o.note('Where corruption is not shown, the offence needs the section 8 presumption.')
o.assert_('NOT `an offence under section 5(b) is made out` `Tan offers, corruption not shown` `$5,000 in cash` FALSE')
o.assert_('`the presumption of section 8 operates` `Lim is a Government officer and Tan has dealings with the Government` `no intermediary`')
o.assert_('`an offence under section 5(b) is made out` `Tan offers, corruption not shown` `$5,000 in cash` (`the presumption of section 8 operates` `Lim is a Government officer and Tan has dealings with the Government` `no intermediary`)')
o.assert_('NOT `the presumption of section 8 operates` `the same, contrary proved` `no intermediary`')
o.assert_('NOT `an offence under section 5(a) is made out` `Tan offers to induce Lim, corruptly` `$5,000 in cash` FALSE')
PU = "(`the punishment for the offence` `Corruption by giving, promising or offering (section 5(b))` `no Government contract`)'s "
o.assert_(PU + '`the maximum fine in dollars` EQUALS 100000')
o.assert_(PU + '`the maximum imprisonment in months` EQUALS 60')
o.section("What the Act hands the Criminal Procedure Code")
S = "(`the Prevention of Corruption Act 1960's statement about its offences`)'s "
o.assert_(S + '`the Act` EQUALS "Prevention of Corruption Act 1960"')
o.assert_(S + '`the Act deems the offence to be an arrestable offence for the purposes of the Criminal Procedure Code 2010`')
o.assert_('NOT ' + S + '`the Act empowers the police to arrest without warrant for the offence`')
o.assert_(S + "`the Act shows the offence as triable by a District Court under that Act`")
o.assert_('NOT ' + S + "`the Act shows the offence as triable by a Magistrate's Court under that Act`")
o.write(os.path.join(enc('prevention-of-corruption-act-1960'), 'pca-tests-scenario-tan.l4'))

# ---------------------------------------------------------------- EA
T = Types(os.path.join(enc('evidence-act-1893'), 'ea-types.l4'))
o = Out(T, "IMPORT prelude\nIMPORT `ea-types`\nIMPORT `ea-statements`\nIMPORT `ea-presumptions-burden`\n\n" + CASE)
o.section("Tan: the offer to Officer Lim, and who must prove the rebuttal")
ADM = ['the statement is oral or documentary', 'the statement suggests an inference as to a fact in issue', 'the maker is a person accused of an offence',
       'the statement states or suggests the inference that the maker committed that offence', 'the maker is a party to the proceeding',
       'the admission is sought to be proved against the maker']
fx(o, "Tan's offer to Lim", 'Admission Facts', ADM)
fx(o, "Tan's offer, made on a condition that it not be proved", 'Admission Facts', ADM + ['the admission was made upon an express condition'])
fx(o, "Tan's offer, civil proceedings, made on that condition", 'Admission Facts', ADM + ['the admission was made upon an express condition', 'the proceedings are civil proceedings'])
fx(o, 'Tan proves his possession was not for trafficking', 'Burden Facts',
   ['the person is accused of an offence', 'a special exception or proviso contained in a law defining the offence'])
fx(o, 'a bare assertion by the prosecution', 'Burden Facts', ['the party who would fail if no evidence at all were given'])
o.assert_("`the admission is relevant and may be proved` `Tan's offer to Lim`")
o.note("Section 23 excludes an admission made on an express condition only in civil proceedings: Tan's offer stays in, in a criminal trial.")
o.assert_("`the admission is relevant and may be proved` `Tan's offer, made on a condition that it not be proved`")
o.assert_("NOT `the admission is relevant and may be proved` `Tan's offer, civil proceedings, made on that condition`")
o.assert_('`the burden of proving the circumstance lies on the accused under section 107` `Tan proves his possession was not for trafficking`')
o.assert_('NOT `the burden of proving the circumstance lies on the accused under section 107` `a bare assertion by the prosecution`')
o.write(os.path.join(enc('evidence-act-1893'), 'ea-tests-scenario-tan.l4'))

# ---------------------------------------------------------------- CPC
T = Types(os.path.join(enc('criminal-procedure-code-2010'), 'cpc-types.l4'))
o = Out(T, "IMPORT prelude\nIMPORT `written-law-interface`\nIMPORT `cpc-types`\nIMPORT `cpc-offence-procedure`\nIMPORT `cpc-second-schedule`\nIMPORT `cpc-other-laws`\n\n" + CASE)
o.section("The statements the two Acts make, as the Acts' own scenario files assert them")
for var, act, deems, empowers in (('the MDA statement', 'Misuse of Drugs Act 1973', 'FALSE', 'TRUE'),
                                  ('the PCA statement', 'Prevention of Corruption Act 1960', 'TRUE', 'FALSE')):
    o.raw('`%s` MEANS `Written Law Procedure Statement` WITH\n'
          '    `the Act` IS "%s"\n'
          '    `the Act deems the offence to be an arrestable offence for the purposes of the Criminal Procedure Code 2010` IS %s\n'
          '    `the Act empowers the police to arrest without warrant for the offence` IS %s\n'
          '    `the Act shows the offence as triable by a District Court under that Act` IS TRUE\n'
          "    `the Act shows the offence as triable by a Magistrate's Court under that Act` IS FALSE\n" % (var, act, deems, empowers))
o.raw('`a silent Act` MEANS `Written Law Procedure Statement` WITH\n'
      '    `the Act` IS "Misuse of Drugs Act 1973"\n'
      '    `the Act deems the offence to be an arrestable offence for the purposes of the Criminal Procedure Code 2010` IS FALSE\n'
      '    `the Act empowers the police to arrest without warrant for the offence` IS FALSE\n'
      '    `the Act shows the offence as triable by a District Court under that Act` IS FALSE\n'
      "    `the Act shows the offence as triable by a Magistrate's Court under that Act` IS FALSE\n")
o.section("Tan: the offence under each Act, as the Code treats it")
fx(o, 'the MDA 5(1) charge', 'Jurisdiction Facts', **{MAXTERM: 20})
fx(o, 'the PCA 5(b) charge', 'Jurisdiction Facts', **{MAXTERM: 5})
o.note("MDA 5(1): 20 years is above s 8(1)'s 10, so a District Court may try it only because MDA s 53 says so (s 9(3)(b)); with a silent Act it may not.")
o.assert_('`the offence under the Act is an arrestable offence` `the MDA 5(1) charge` `the MDA statement`')
o.assert_('`a District Court may try the offence under the Act` `the MDA 5(1) charge` `the MDA statement`')
o.assert_('NOT `a District Court may try the offence under the Act` `the MDA 5(1) charge` `a silent Act`')
o.assert_("NOT `a Magistrate's Court may try the offence under the Act` `the MDA 5(1) charge` `the MDA statement`")
o.note("PCA 5(b): 5 years, so a Magistrate's Court may try it under s 7(1)(a) although the Act is silent on Magistrates; arrestable because PCA s 32(1) deems it so.")
o.assert_('`the offence under the Act is an arrestable offence` `the PCA 5(b) charge` `the PCA statement`')
o.assert_("`a Magistrate's Court may try the offence under the Act` `the PCA 5(b) charge` `the PCA statement`")
o.assert_('`a District Court may try the offence under the Act` `the PCA 5(b) charge` `the PCA statement`')
o.section("Tan: the criminal case disclosure procedures (Second Schedule, s 159)")
o.assert_('`the Act\'s offence is under a law specified in the Second Schedule` `the MDA statement` "5"')
o.assert_('`the Act\'s offence is under a law specified in the Second Schedule` `the PCA statement` "5"')
fx(o, 'tried in a District Court, no consent', 'State Court Disclosure Facts', ['the offence is to be tried in a District Court'])
fx(o, "tried in a Magistrate's Court, no consent", 'State Court Disclosure Facts')
WM = "(`the written law offence facts for the Act's offence` `the MDA statement` \"5\")"
WP = "(`the written law offence facts for the Act's offence` `the PCA statement` \"5\")"
o.assert_('`the criminal case disclosure procedures of Part 9 apply` %s `tried in a District Court, no consent`' % WM)
o.assert_('`the criminal case disclosure procedures of Part 9 apply` %s `tried in a District Court, no consent`' % WP)
o.assert_("NOT `the criminal case disclosure procedures of Part 9 apply` %s `tried in a Magistrate's Court, no consent`" % WP)
o.write(os.path.join(enc('criminal-procedure-code-2010'), 'cpc-tests-scenario-tan.l4'))
print("written")
