def q(x): return '`%s`' % x


class Suite:
    def __init__(self, header):
        self.o = Out(types, header)
    def case(self, name, rec, *true, **vals):
        self.o.case(name, rec, *true, **vals)
    def yes(self, pred, *args):
        self.o.assert_('`%s` %s' % (pred, ' '.join(a if a in ('TRUE', 'FALSE') or a.startswith('(') else q(a) for a in args)))
    def no(self, pred, *args):
        self.o.assert_('NOT `%s` %s' % (pred, ' '.join(a if a in ('TRUE', 'FALSE') or a.startswith('(') else q(a) for a in args)))
    def section(self, t): self.o.section(t)


