o.assert_('NOT `the criminal case disclosure procedures of Part 10 Division 5 apply` `Road Traffic Act offence` `designated for the High Court`')
o.assert_('NOT `the criminal case disclosure procedures of Part 10 Division 5 apply` `Road Traffic Act offence` `neither`')
o.assert_('NOT `the criminal case disclosure procedures of Part 10 Division 5 apply` `Road Traffic Act offence` `neither, with consent`')
o.assert_('`the criminal case disclosure procedures of Part 10 Division 5 apply` `Penal Code offence` `designated for the High Court`')
o.assert_('NOT `the criminal case disclosure procedures of Part 10 Division 5 apply` `Immigration Act s 15` `designated for the High Court`')
